    export_formats(e2e_cases, "end-to-end")
    all_cases.extend(e2e_cases)
    
    # 9. Security
    sec_cases = generate_combinations("TC-SEC", ["Auth System", "Data Storage", "API Endpoints", "File Uploads"], ["SQL Injection", "XSS Injection", "CSRF Attack", "Path Traversal"], ["admin role", "guest role", "unauthenticated"], ["Payload sanitized", "Access Denied", "No sensitive data leaked"])
