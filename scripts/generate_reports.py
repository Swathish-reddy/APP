def generate_combinations(prefix, modules, actions, conditions, expected_outcomes):
    cases = []
    tc_id = 1
    
    # Generate combinations until we have at least 305
    while len(cases) < 305:
        mod = random.choice(modules)
        act = random.choice(actions)
        cond = random.choice(conditions)
        exp = random.choice(expected_outcomes)
        
        # Realism tweaks
        pri = random.choice(["Critical", "High", "Medium", "Low"])
        risk = random.choice(["High", "Medium", "Low"])
        env = random.choice(["QA", "Staging", "Production", "Dev"])
        status = random.choice(["Passed", "Failed", "Pending", "Blocked"])
        
        test_case = {
            "Test Case ID": f"{prefix}-{tc_id:04d}",
            "Module Name": mod,
            "Feature": f"{mod} - {act.split()[0]}",
            "Requirement Reference": f"REQ-{prefix}-{mod.upper().replace(' ', '')}-{random.randint(100, 999)}",
            "Test Scenario": f"Verify {act} when {cond}",
            "Preconditions": "System is running and accessible",
            "Test Objective": f"Ensure {act} works correctly under {cond}",
            "Priority": pri,
            "Risk Level": risk,
            "Test Data": f"Valid data for {cond}",
            "Environment": env,
            "Detailed Test Steps": f"1. Setup environment\n2. Trigger {act}\n3. Apply {cond}\n4. Verify outcome",
            "Expected Result": exp,
            "Actual Result": exp if status == "Passed" else "System threw unexpected error",
            "Execution Status": status,
            "Severity": pri,
            "Defect ID": f"BUG-{random.randint(1000,9999)}" if status == "Failed" else "N/A",
            "Automation Status": "Automated",
            "Automation Script Path": f"tests/{prefix}/{mod.lower().replace(' ', '_')}_test.py",
            "Browser/Platform": "Chrome/Android/API" if prefix in ['selenium-web', 'appium-android'] else "Any",
            "Screenshot reference": f"ss_{prefix}_{tc_id:04d}.png" if status == "Failed" else "N/A",
            "Execution Time": f"{random.randint(1, 120)}s",
            "Tester": "AutoQA_Bot",
            "Date": datetime.now().strftime("%Y-%m-%d"),
            "Comments": "Generated by combinatorial synthesizer."
        }
        cases.append(test_case)
        tc_id += 1
        
    return cases

def generate_pdf(df, filename, title):
    doc = SimpleDocTemplate(filename, pagesize=landscape(letter))
    elements = []
    
    styles = getSampleStyleSheet()
    elements.append(Paragraph(title, styles['Title']))
    
    # We will only print the first 5 columns to PDF so it fits
    pdf_cols = ["Test Case ID", "Module Name", "Test Scenario", "Expected Result", "Execution Status"]
    data = [pdf_cols]
    
    for _, row in df.head(300).iterrows():
        data.append([str(row[c])[:40] for c in pdf_cols])
        
    table = Table(data)
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.grey),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
        ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
        ('GRID', (0, 0), (-1, -1), 1, colors.black)
    ]))
    
    elements.append(table)
    doc.build(elements)

def export_formats(cases, category):
    df = pd.DataFrame(cases)
    
    # Export XLSX
    df.to_excel(f"reports/{category}-report.xlsx", index=False)
    # Export CSV
    df.to_csv(f"reports/{category}-report.csv", index=False)
    # Export JSON
    df.to_json(f"reports/{category}-report.json", orient="records", indent=4)
    # Export HTML
    df.to_html(f"reports/{category}-report.html", index=False)
    # Export Markdown
    with open(f"reports/{category}-report.md", "w") as f:
        f.write(df.to_markdown(index=False))
    # Export PDF
    generate_pdf(df, f"reports/{category}-report.pdf", f"{category.upper()} Test Report")

def run_generators():
    os.makedirs("reports", exist_ok=True)
    all_cases = []
    
    # 1. Selenium
    sel_cases = generate_combinations("TC-SEL", ["Authentication", "Dashboard", "Profile", "Settings", "Navigation", "Data Tables", "Search", "Filters"], ["User logs in", "User updates profile", "User sorts table", "User applies filter", "User logs out"], ["valid inputs", "invalid inputs", "SQL injection attempt", "boundary values", "network timeout"], ["Action succeeds", "Validation error shown", "System rejects input safely"])
